internal enum class LabTechnique {
    TITRATION, CALORIMETRY, KINETICS, EQUILIBRIUM, ELECTROCHEMISTRY,
    SOLUBILITY, SEPARATION, GAS, QUALITATIVE, SYNTHESIS,
    GRAVIMETRY, SPECTROSCOPY, PHYSICAL_MEASUREMENT
}

internal data class VirtualExperiment(
    val id: String,
    val title: String,
    val category: String,
    val level: String,
    val technique: LabTechnique,
    val objective: String,
    val equation: String,
    val apparatus: String,
    val reagents: String,
    val safety: String,
    val procedure: List<String>,
    val measuredQuantity: String,
    val referenceValue: Double,
    val unit: String,
    val analysis: String,
    val theory: String,
    val expectedResult: String
)

private fun experiment(
    id: String, title: String, category: String, level: String, technique: LabTechnique,
    objective: String, equation: String, apparatus: String, reagents: String, safety: String,
    measuredQuantity: String, referenceValue: Double, unit: String, analysis: String,
    vararg procedure: String
) = VirtualExperiment(
    id, title, category, level, technique, objective, equation, apparatus, reagents, safety,
    procedure.toList(), measuredQuantity, referenceValue, unit, analysis,
    theory = techniqueTheory(technique, equation),
    expectedResult = expectedExperimentResult(technique, measuredQuantity, referenceValue, unit)
)

private fun techniqueTheory(technique: LabTechnique, equation: String): String = when (technique) {
    LabTechnique.TITRATION -> "At the equivalence point, reactants have been combined in the mole ratio shown by $equation. Accurate volumetric glassware converts the measured delivered volume into an amount of substance."
    LabTechnique.CALORIMETRY -> "Energy conservation relates reaction heat to the surroundings: q = mcΔT. The molar enthalpy follows after correcting the sign and dividing by the limiting-reagent amount."
    LabTechnique.KINETICS -> "Reaction rate is the change in concentration or measurable signal per unit time. Controlled trials reveal how concentration, temperature and catalysts affect collision frequency and activation."
    LabTechnique.EQUILIBRIUM -> "A reversible system reaches dynamic equilibrium when forward and reverse rates are equal. Equilibrium concentrations, not starting concentrations, belong in the equilibrium-constant expression for $equation."
    LabTechnique.ELECTROCHEMISTRY -> "Oxidation at the anode supplies electrons and reduction consumes them at the cathode. Cell voltage follows electrode potentials and, away from standard conditions, the Nernst equation."
    LabTechnique.SOLUBILITY -> "A saturated solution is in dynamic equilibrium with undissolved solid. The solubility product uses equilibrium ion concentrations raised to their stoichiometric powers."
    LabTechnique.SEPARATION -> "Components separate because they differ in volatility, adsorption, partitioning or solubility. Good technique balances recovery with purity and minimizes transfer loss."
    LabTechnique.GAS -> "Gas pressure, volume, amount and absolute temperature are linked by PV = nRT. Wet-gas measurements require vapor-pressure and pressure-level corrections."
    LabTechnique.QUALITATIVE -> "Selective reagents convert chemical identity into an observable color, precipitate or gas. A blank, known reference and independent confirmation reduce false identification."
    LabTechnique.SYNTHESIS -> "Stoichiometry determines theoretical yield, while kinetics and equilibrium influence conversion. Isolation, purification and characterization are required before yield alone is meaningful."
    LabTechnique.GRAVIMETRY -> "The analyte is converted quantitatively into a pure compound of known formula. Constant dry mass and stoichiometric mass factors allow the original analyte amount to be calculated."
    LabTechnique.SPECTROSCOPY -> "Beer–Lambert law, A = εlc, relates absorbance to path length and concentration at a fixed wavelength. A blank and calibration standards establish the quantitative response."
    LabTechnique.PHYSICAL_MEASUREMENT -> "A physical property is measured under stated conditions and compared with a reference. Calibration, thermal equilibrium, replicate readings and uncertainty control the result quality."
}

private fun expectedExperimentResult(
    technique: LabTechnique,
    quantity: String,
    value: Double,
    unit: String
): String {
    val valueText = when {
        kotlin.math.abs(value) < .001 && value != 0.0 -> "%.2e".format(value)
        kotlin.math.abs(value) < 10 -> "%.3f".format(value)
        kotlin.math.abs(value) < 100 -> "%.2f".format(value)
        else -> "%.1f".format(value)
    }
    val observation = when (technique) {
        LabTechnique.TITRATION -> "A sharp endpoint or instrumental break should occur near the equivalence volume; concordant trials should agree closely."
        LabTechnique.CALORIMETRY -> "The temperature should move smoothly to a maximum or minimum, then drift back as heat exchanges with the surroundings."
        LabTechnique.KINETICS -> "The signal should change fastest initially and approach a plateau as a limiting reactant is consumed."
        LabTechnique.EQUILIBRIUM -> "Replicate mixtures should give a consistent equilibrium constant within experimental uncertainty."
        LabTechnique.ELECTROCHEMISTRY -> "The voltage should stabilize with the predicted polarity when the circuit is measured without significant current."
        LabTechnique.SOLUBILITY -> "Saturation, first persistent turbidity or recovered crystals should occur reproducibly at controlled temperature."
        LabTechnique.SEPARATION -> "Distinct fractions, bands or phases should form, with measurable enrichment of the target component."
        LabTechnique.GAS -> "Corrected gas data should follow the predicted proportionality and give a near-linear transformed plot."
        LabTechnique.QUALITATIVE -> "The unknown should reproduce the characteristic response of the reference and pass the confirmation test."
        LabTechnique.SYNTHESIS -> "An isolated purified product should have the expected appearance/property and a realistic yield below the theoretical maximum."
        LabTechnique.GRAVIMETRY -> "A clean precipitate or residue should reach constant mass in successive heat–cool–weigh cycles."
        LabTechnique.SPECTROSCOPY -> "Blank-corrected standards should form a straight calibration line and the unknown should lie inside that range."
        LabTechnique.PHYSICAL_MEASUREMENT -> "Replicate readings should cluster near the reference when temperature and instrument calibration are controlled."
    }
    return "$quantity should be close to $valueText $unit. $observation"
}

